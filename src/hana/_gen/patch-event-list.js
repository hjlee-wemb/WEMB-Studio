/* 이벤트 리스트의 단추들을 살린다 — 등급 칩 · 조회 · 초기화 · 삭제 · 줄 고르기.
   ─────────────────────────────────────────────────────────────────────────────
   대상은 두 가지다(둘 다 같은 코드로 다룬다).
     · `[data-name="Event Log"]`        하단 이벤트 현황 바 (9화면)
     · `[data-name^="Widget/Event Log"]` 이벤트현황 큰 표 · 상면 팝업 · 보안 로그

   ── 시안에 박혀 있던 '상태 본보기 줄' ──
   Figma 는 hover·active 가 어떻게 보이는지 알려 주려고 **그 상태의 줄을 하나씩 끼워** 뒀다.
   그대로 옮기면 늘 그 색으로 앉아 있어, 가만히 있는데도 한 줄은 눌린 것처럼 보인다.
     · 상면관리  `#hnf-row_2`(rgba(35,77,72,.3)) = hover, `.n1_2539`(rgba(0,145,120,.3)) = active
     · 이벤트현황 `status=hover` · `status=active` (이름으로 대놓고 알려 준다)
     · 그 밖에도 11개 리스트 중 10개에 hover 본보기가, 3개에 active 본보기가 들어 있다.
   → **본보기 줄은 쉴 때 보통 줄처럼 되돌리고, 그 색을 진짜 hover·고름 상태에 쓴다.**
     색을 새로 짓지 않고 **시안이 준 클래스를 그대로 갈아 끼우므로** 라이트 테마와
     '색 정하기'가 저절로 따라온다.

   ── 줄을 이름으로 찾으면 안 된다 ──
   `.n1_2539` 처럼 `data-name` 이 없는 줄이 있다(상면관리 active 본보기가 그렇다).
   이름 대신 **줄 담는 상자의 자식 중 칸이 3개 이상인 것**을 줄로 본다.

   ── 단추 ──
   · 등급 칩(심각·경계·주의·정상) — 그 등급만 남기고 나머지는 흐린다. 다시 누르면 풀린다.
     지우지 않고 흐리는 이유는 걸러 낸 결과가 0줄일 때 표가 텅 비기 때문이다.
   · 조회 — 업무그룹·호스트 칸의 글자가 든 줄만 남긴다(칸이 비면 전부).
   · 초기화 — 등급·검색을 풀고 지웠던 줄까지 되살린다.
   · 삭제 — 고른 줄을 지운다. 고른 줄이 없으면 아무 일도 하지 않는다.
   편집 중(패널편집)에는 전부 쉰다. */
