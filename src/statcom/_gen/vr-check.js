/* VR 4장 점검 — 1920x1080 미리보기 캡처 + 스튜디오에서 흐름 · 편집 · 테마를 눌러 본다. Playwright filename */
async (page) => {
  const GEN = 'C:/Users/wemb/Desktop/진행중/디자인팀/1_WEMB STUDIO/WEMB Studio/src/statcom/_gen/';
  const out = {};
  await page.setViewportSize({ width: 1920, height: 1080 });
  const cap = async (pg, name) => {
    await page.goto('http://localhost:5542/src/statcom/' + pg + '.html?t=dark&r=' + Date.now());
    await page.evaluate(() => document.fonts.ready);
    await page.waitForTimeout(1000);
    await page.screenshot({ path: GEN + 'thumb-' + name + '.png' });
    await page.setViewportSize({ width: 1248, height: 852 });
    await page.waitForTimeout(250);
    const m = await page.evaluate(() => { const r = document.querySelector('.tc-root').getBoundingClientRect(), f = document.querySelector('.tc-root > [data-node-id]').getBoundingClientRect(), s = document.querySelector('[data-name="Scene Image"]').getBoundingClientRect(); return { frame: [f.left - r.left, f.top - r.top, r.right - f.right, r.bottom - f.bottom].map((v) => +v.toFixed(1)), scene: [s.left - r.left, s.top - r.top, r.right - s.right, r.bottom - s.bottom].map((v) => +v.toFixed(1)) }; });
    await page.setViewportSize({ width: 1920, height: 1080 });
    return m;
  };
  out.fit = {};
  for (const n of ['vr-topic', 'vr-menu', 'vr-step', 'vr-overview']) out.fit[n] = await cap(n, n);

  const ctx = await page.context().browser().newContext({ viewport: { width: 1920, height: 1080 } });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push('PAGE ' + String(e).slice(0, 220)));
  p.on('console', (m) => { if ((m.type() === 'error' || (m.type() === 'warning' && /\[tc\]/.test(m.text()))) && !/favicon|ERR_|404|WebSocket|api\//.test(m.text())) errs.push(m.text().slice(0, 220)); });
  await p.goto('http://localhost:5542/index.html#/templates/digital-twin-statcom-hmi');
  await p.waitForTimeout(1200);
  out.slides = await p.evaluate(() => document.querySelectorAll('button, a').length && /\/ 15/.test(document.body.innerText));
  await p.evaluate(() => { [...document.querySelectorAll('button, a')].find((x) => /스튜디오 열기/.test(x.textContent)).click(); });
  await p.waitForSelector('#dtStage .tcm-root', { timeout: 15000 });
  await p.waitForTimeout(1200);
  out.screens = await p.evaluate(() => { const P = WEMB.projects; const me = P.loadProjects().find((x) => x.id === localStorage.getItem(P.CUR_PROJ)); return P.loadProjects().filter((x) => x.projectId === me.projectId).map((x) => x.tplScene).join(','); });
  const click = async (sel) => { const r = await p.evaluate((s) => { const e = document.querySelector(s); if (!e) return null; const b = e.getBoundingClientRect(); return [b.left + b.width / 2, b.top + b.height / 2]; }, sel); if (r) await p.mouse.click(r[0], r[1]); return !!r; };
  const at = async (px, ms) => { await p.waitForSelector('#dtStage .' + px + '-root', { timeout: 6000 }).catch(() => {}); await p.waitForTimeout(ms || 500); return p.evaluate((x) => !!document.querySelector('#dtStage .' + x + '-root'), px); };
  await p.evaluate(() => window.__gotoStatcomScene('vr-topic'));
  out.flow = {};
  out.flow.topic = await at('tvt', 1000);
  await p.screenshot({ path: GEN + 'vr-studio-topic.png' });
  await click('#dtStage [data-name="Button/MMC Valve Submodule Replacement"]');
  out.flow.overview = await at('tvo', 800);
  await p.screenshot({ path: GEN + 'vr-studio-overview.png' });
  await click('#dtStage [data-name="Button/Start Training"]');
  out.flow.step = await at('tvs', 800);
  await p.keyboard.press('m');
  out.flow.menuByM = await at('tvm', 800);
  const box = await p.evaluate(() => { const b = document.querySelector('#dtStage [data-name="Button/Restart"]').getBoundingClientRect(); return [b.left + b.width / 2, b.top + b.height / 2]; });
  const srcA = await p.evaluate(() => document.querySelector('#dtStage [data-name="Button/Restart"] img').getAttribute('src'));
  await p.mouse.move(box[0], box[1]); await p.waitForTimeout(250);
  const srcB = await p.evaluate(() => document.querySelector('#dtStage [data-name="Button/Restart"] img').getAttribute('src'));
  out.hoverSwap = srcA !== srcB;
  await p.screenshot({ path: GEN + 'vr-studio-menu.png' });
  await p.keyboard.press('Escape');
  out.flow.stepByEsc = await at('tvs', 600);
  await p.evaluate(() => window.__gotoStatcomScene('vr-overview'));
  await at('tvo', 600);
  await p.evaluate(() => document.querySelector('#mode button[data-m="light"]').click());
  await p.waitForTimeout(1400);
  await p.screenshot({ path: GEN + 'vr-studio-light.png' });
  await p.evaluate(() => document.querySelector('#mode button[data-m="dark"]').click());
  await p.waitForTimeout(600);
  await p.evaluate(() => document.getElementById('editAll').click());
  await p.waitForTimeout(700);
  out.edit = await p.evaluate(() => { const r = document.querySelector('.tvo-root'); const ps = [...r.querySelectorAll('p, li')]; return { total: ps.length, editable: ps.filter((x) => x.isContentEditable).length }; });
  const g = await p.evaluate(() => { const b = document.querySelector('.tvo-root [data-name="Header Bar"]').getBoundingClientRect(); return [b.left + 40, b.top + 18]; });
  const y0 = await p.evaluate(() => document.querySelector('.tvo-root [data-name^="Popup/"]').getBoundingClientRect().top);
  await p.mouse.move(g[0], g[1]); await p.mouse.down(); await p.mouse.move(g[0] + 50, g[1] + 40, { steps: 8 }); await p.mouse.up(); await p.waitForTimeout(700);
  const y1 = await p.evaluate(() => document.querySelector('.tvo-root [data-name^="Popup/"]').getBoundingClientRect().top);
  out.moved = +(y1 - y0).toFixed(1);
  await p.evaluate(() => document.getElementById('editAll').click());
  out.errs = errs.slice(0, 12);
  await ctx.close();
  return out;
}
